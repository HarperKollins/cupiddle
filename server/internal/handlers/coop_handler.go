// StartGame initiates a new Co-op Corner activity
func (h *CoopHandler) StartGame(w http.ResponseWriter, r *http.Request) {
	currentUserID, _ := r.Context().Value(middleware.UserIDKey).(string)
	convID := chi.URLParam(r, "id")

	var u1, u2 string
	err := h.DB.QueryRow("SELECT user1_id, user2_id FROM conversations WHERE id = $1", convID).Scan(&u1, &u2)
	if err != nil || (u1 != currentUserID && u2 != currentUserID) {
		respondJSON(w, http.StatusForbidden, map[string]string{"error": "access denied to conversation"})
		return
	}

	partnerID := u1
	if partnerID == currentUserID {
		partnerID = u2
	}

	var req StartGameRequest
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		respondJSON(w, http.StatusBadRequest, map[string]string{"error": "invalid request body"})
		return
	}

	gameID := uuid.New().String()
	now := time.Now()

	title := "Co-op Logic Riddle"
	promptData := curatedRiddles[rand.Intn(len(curatedRiddles))].PromptData

	if req.GameType == "would_you_rather" {
		item := curatedWouldYouRather[rand.Intn(len(curatedWouldYouRather))]
		title = item.Title
		promptData = item.PromptData
	} else if req.GameType == "two_truths_lie" {
		title = "Two Truths & A Lie"
		promptData = `{"instruction":"Submit two extraordinary true facts and one plausible lie about yourself!"}`
	} else if req.GameType == "ai_or_human" {
		title = "AI or Human Prose Challenge"
		promptData = `{"excerpt":"Memory is an accordion: it shrinks when you want to linger, and stretches when you want to pass quickly through the dark hallways of the mind.", "question":"Was this metaphor generated by Claude 3.5 or written by Vladimir Nabokov?"}`
	}

	_, err = h.DB.Exec(
		`INSERT INTO coop_games (id, conversation_id, game_type, initiator_id, partner_id, title, prompt_data, status, created_at)
		 VALUES ($1, $2, $3, $4, $5, $6, $7, 'in_progress', $8)`,
		gameID, convID, req.GameType, currentUserID, partnerID, title, promptData, now,
	)
	if err != nil {
		respondJSON(w, http.StatusInternalServerError, map[string]string{"error": "failed to start game"})
		return
	}

	game := models.CoopGame{
		ID:             gameID,
		ConversationID: convID,
		GameType:       req.GameType,
		InitiatorID:    currentUserID,
		PartnerID:      partnerID,
		Title:          title,
		PromptData:     promptData,
		Status:         "in_progress",
		CreatedAt:      now,
	}

	if h.Hub != nil {
		h.Hub.SendToUser(partnerID, "coop_turn", game)
	}

	respondJSON(w, http.StatusCreated, game)
}

// GetActiveGame fetches the in-progress game for this conversation
func (h *CoopHandler) GetActiveGame(w http.ResponseWriter, r *http.Request) {
	convID := chi.URLParam(r, "id")

	var g models.CoopGame
	var resultSummary *string
	var completedAt *time.Time

	err := h.DB.QueryRow(
		`SELECT id, conversation_id, game_type, initiator_id, partner_id, title, prompt_data,
		        user1_answer, user2_answer, status, result_summary, created_at, completed_at
		 FROM coop_games
		 WHERE conversation_id = $1 AND status = 'in_progress'
		 ORDER BY created_at DESC LIMIT 1`, convID,
	).Scan(
		&g.ID, &g.ConversationID, &g.GameType, &g.InitiatorID, &g.PartnerID, &g.Title, &g.PromptData,
		&g.User1Answer, &g.User2Answer, &g.Status, &resultSummary, &g.CreatedAt, &completedAt,
	)
	if err != nil {
		respondJSON(w, http.StatusOK, map[string]interface{}{"active_game": nil})
		return
	}

	if resultSummary != nil {
		g.ResultSummary = *resultSummary
	}
	g.CompletedAt = completedAt

	respondJSON(w, http.StatusOK, map[string]interface{}{"active_game": g})
}

// SubmitAnswer submits a turn or guess in the game
func (h *CoopHandler) SubmitAnswer(w http.ResponseWriter, r *http.Request) {
	currentUserID, _ := r.Context().Value(middleware.UserIDKey).(string)
	gameID := chi.URLParam(r, "gameId")

	var g models.CoopGame
	err := h.DB.QueryRow(
		`SELECT id, conversation_id, game_type, initiator_id, partner_id, title, prompt_data,
		        user1_answer, user2_answer, status
		 FROM coop_games WHERE id = $1`, gameID,
	).Scan(&g.ID, &g.ConversationID, &g.GameType, &g.InitiatorID, &g.PartnerID, &g.Title, &g.PromptData, &g.User1Answer, &g.User2Answer, &g.Status)
	if err != nil {
		respondJSON(w, http.StatusNotFound, map[string]string{"error": "game not found"})
		return
	}

	var req SubmitAnswerRequest
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil || len(req.Answer) == 0 {
		respondJSON(w, http.StatusBadRequest, map[string]string{"error": "answer is required"})
		return
	}

	now := time.Now()
	if currentUserID == g.InitiatorID {
		g.User1Answer = req.Answer
		h.DB.Exec("UPDATE coop_games SET user1_answer = $1 WHERE id = $2", req.Answer, gameID)
	} else if currentUserID == g.PartnerID {
		g.User2Answer = req.Answer
		h.DB.Exec("UPDATE coop_games SET user2_answer = $1 WHERE id = $2", req.Answer, gameID)
	} else {
		respondJSON(w, http.StatusForbidden, map[string]string{"error": "not a player in this game"})
		return
	}

	// Check if both have answered
	if g.User1Answer != "" && g.User2Answer != "" {
		g.Status = "completed"
		g.ResultSummary = "Both players submitted their answers! Compare your logic in chat."
		g.CompletedAt = &now
		h.DB.Exec(
			"UPDATE coop_games SET status = 'completed', result_summary = $1, completed_at = $2 WHERE id = $3",
			g.ResultSummary, now, gameID,
		)
	}

	// Notify partner
	partnerID := g.PartnerID
	if currentUserID == g.PartnerID {
		partnerID = g.InitiatorID
	}
	if h.Hub != nil {
		h.Hub.SendToUser(partnerID, "coop_turn", g)
	}

	respondJSON(w, http.StatusOK, g)
}

