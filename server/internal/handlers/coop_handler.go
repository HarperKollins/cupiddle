// CoopHandler manages Co-op Corner mini-games inside conversations
type CoopHandler struct {
	DB  *database.DB
	Hub *websocket.Hub
}

// NewCoopHandler creates a new CoopHandler
func NewCoopHandler(db *database.DB, hub *websocket.Hub) *CoopHandler {
	return &CoopHandler{DB: db, Hub: hub}
}

type StartGameRequest struct {
	GameType string `json:"game_type"` // "logic_riddle", "would_you_rather", "two_truths_lie", "ai_or_human"
}

type SubmitAnswerRequest struct {
	Answer string `json:"answer"`
}

